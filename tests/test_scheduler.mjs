import assert from 'node:assert/strict';
import worker,{tick} from '../deployment/cloudflare/scheduler/worker.mjs';
const now=Date.parse('2026-11-10T12:12:00Z');
const records=new Map();
const env={GITHUB_DISPATCH_TOKEN:'test-only',DATA:{async get(k){return records.has(k)?{async json(){return JSON.parse(records.get(k))}}:null},async put(k,v){records.set(k,v)}}};
let calls=[];
const network=async(url,options)=>{calls.push({url,options});return options.method==='POST'?new Response(null,{status:204}):Response.json({workflow_runs:[]})};
assert.equal((await tick({...env,GITHUB_DISPATCH_TOKEN:''},now,network)).status,'needs_github_token');assert.equal(calls.length,0);
records.set('public/current.json',JSON.stringify({forecast_issued_at:'2026-11-10T12:02:00Z'}));
assert.equal((await tick(env,now,network)).status,'current_hour_saved');assert.equal(calls.length,0);
records.set('public/current.json',JSON.stringify({forecast_issued_at:'2026-11-10T07:45:00Z'}));
assert.equal((await tick(env,now,network)).status,'dispatched');assert.equal(calls.length,2);
assert.equal(calls[1].options.body,'{"ref":"main"}');
assert(!records.get('state/scheduler.json').includes('test-only'));
assert.equal((await tick(env,now,async()=>Response.json({workflow_runs:[{status:'in_progress',created_at:'2026-11-10T12:10:00Z'}]}))).status,'forecast_job_pending');
await assert.rejects(()=>tick(env,now,async()=>new Response(null,{status:403})),/lookup failed: 403/);
assert.equal(JSON.parse(records.get('state/scheduler.json')).status,'github_read_failed');
assert.equal((await worker.fetch(new Request('https://test/dispatch',{method:'POST'}),env)).status,404);
console.log('Scheduler duplicate suppression, pending jobs, dispatch, secret isolation and failures passed.');
